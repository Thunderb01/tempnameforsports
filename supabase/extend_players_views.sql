-- ============================================================
-- Extend vw_players / vw_w_players to expose player_status and the new
-- transfer_* fields (added in add_transfer_fields.sql).
--
-- Neither view previously exposed player_status at all — useRosterBoard.js
-- worked around this with a second query straight against the base table.
-- Adding it here (plus the transfer_* fields) lets board/rankings/roster
-- code read everything off one row instead of a second round-trip.
--
-- New columns are appended at the end of each SELECT list — Postgres
-- requires CREATE OR REPLACE VIEW to preserve existing column order/types,
-- appending is the only safe way to extend without a drop+recreate.
--
-- Safe to run more than once.
-- ============================================================

create or replace view public.vw_players as
 SELECT p.id,
    p.name,
    p.current_team,
    p.primary_position,
    p.year,
    p.height,
    p.hometown,
    p.espn_id,
    p.source,
    p.open_market_low,
    p.open_market_high,
    p.nil_valuation,
    s.ppg,
    s.rpg,
    s.apg,
    s.usg,
    s.ast_tov,
    s.fg_pct,
    s."3p_pct",
    s.ft_pct,
    s.sei,
    s.ath,
    s.ris,
    s.dds,
    s.cdi,
    s.conference,
    s.calendar_year,
    p.player_status,
    p.transfer_status,
    p.transfer_from_team,
    p.transfer_to_team,
    p.transfer_season_year,
    p.transfer_api_id,
    p.positions
   FROM players p
     LEFT JOIN LATERAL ( SELECT player_stats.id,
            player_stats.player_id,
            player_stats.year,
            player_stats.ppg,
            player_stats.rpg,
            player_stats.apg,
