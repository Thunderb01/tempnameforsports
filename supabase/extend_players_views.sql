            player_stats.atr_pct,
            player_stats.stl_40,
            player_stats.blk_40,
            player_stats.drb_40,
            player_stats.orb_40,
            player_stats.trb_40,
            player_stats.cdi,
            player_stats.dds,
            player_stats.sei,
            player_stats.smi,
            player_stats.ris,
            player_stats.created_at,
            player_stats.calendar_year,
            player_stats.name,
            player_stats.torvik_ortg,
            player_stats.torvik_usg,
            player_stats.torvik_efg,
            player_stats.torvik_ts,
            player_stats.torvik_obpm,
            player_stats.torvik_dbpm,
            player_stats.torvik_bpm,
            player_stats.torvik_drtg,
            player_stats.torvik_stops,
            player_stats.torvik_ast_pct,
            player_stats.torvik_to_pct,
            player_stats.torvik_orb_pct,
            player_stats.torvik_drb_pct,
            player_stats.torvik_rim_pct,
            player_stats.torvik_mid_pct,
            player_stats.torvik_3p_pct,
            player_stats.torvik_porpag,
            player_stats.torvik_adjoe,
            player_stats.torvik_min_pct,
            player_stats.torvik_gp,
            player_stats.ast_40,
            player_stats.tot_g,
            player_stats.tot_gs,
            player_stats.tot_mp,
            player_stats.tot_fg,
            player_stats.tot_fga,
            player_stats.tot_3p,
            player_stats.tot_3pa,
            player_stats.tot_2p,
            player_stats.tot_2pa,
